    }

    fun getHadithsForBook(bookId: String): List<Hadith> {
        return ENCYCLOPEDIC_HADITHS.filter { it.bookId == bookId }
    }

    fun getHadithById(hadithId: String): Hadith? {
        return ENCYCLOPEDIC_HADITHS.find { it.id == hadithId }
    }
